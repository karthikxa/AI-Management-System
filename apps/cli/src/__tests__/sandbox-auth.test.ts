import { afterEach, beforeEach, describe, expect, it } from 'bun:test';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { activeHost } from '../api/config.ts';
import { createApiClient } from '../api/client.ts';
import { resolveProjectContext } from '../command-helpers.ts';
import { connectorProjectContext } from '../connector-gateway/gateway.ts';
import { resolveProjectId } from '../project-link.ts';

// These tests pin the contract the platform relies on when it injects auth
// into a session sandbox: ZED_CLI_TOKEN carries the session connector PAT,
// ZED_API_URL already includes the `/v1` mount, and
// ZED_PROJECT_ID selects the project — all read with zero config files.

const ENV_KEYS = [
  'ZED_CLI_TOKEN',
  'ZED_TOKEN',
  'ZED_API_URL',
  'ZED_PROJECT_ID',
  'BASH_ENV',
  'ZED_DISABLE_SANDBOX_ENV_FILE',
  'ZED_CONFIG_FILE',
  'ZED_AUTH_FILE',
] as const;

let saved: Record<string, string | undefined>;

beforeEach(() => {
  saved = {};
  for (const k of ENV_KEYS) {
    saved[k] = process.env[k];
    delete process.env[k];
  }
  // Point config storage at a path that does not exist so no real auth leaks in.
  process.env.ZED_CONFIG_FILE = '/nonexistent/zed-test-config.json';
  process.env.ZED_DISABLE_SANDBOX_ENV_FILE = '1';
});

afterEach(() => {
  for (const k of ENV_KEYS) {
    if (saved[k] === undefined) delete process.env[k];
    else process.env[k] = saved[k];
  }
});

describe('in-sandbox auth resolution', () => {
  it('uses ZED_CLI_TOKEN as the active token', () => {
    process.env.ZED_CLI_TOKEN = 'zed_pat_cli';
    process.env.ZED_API_URL = 'https://tunnel.example/v1';
    const host = activeHost();
    expect(host?.token).toBe('zed_pat_cli');
    expect(host?.url).toBe('https://tunnel.example/v1');
  });

  it('loads sandbox CLI auth from BASH_ENV agent-env.sh when non-interactive shells did not source it', () => {
    const dir = mkdtempSync(join(tmpdir(), 'zed-cli-agent-env-'));
    const envFile = join(dir, 'agent-env.sh');
    try {
      writeFileSync(
        envFile,
        [
          '# Generated by Zed agent sandbox session.',
          "export ZED_CLI_TOKEN='zed_pat_from_file'",
          "export ZED_API_URL='https://dev-api.zed.com/v1'",
          "export ZED_FRONTEND_URL='https://dev.zed.com'",
          "export ZED_PROJECT_ID='proj-from-file'",
          "export NOT_ALLOWLISTED='must-not-be-imported'",
          "export AGENTMAIL_API_KEY='must-not-be-imported'",
          '',
        ].join('\n'),
      );
      delete process.env.ZED_DISABLE_SANDBOX_ENV_FILE;
      process.env.BASH_ENV = envFile;

      const host = activeHost();
      expect(host?.token).toBe('zed_pat_from_file');
      expect(host?.url).toBe('https://dev-api.zed.com/v1');
      expect(resolveProjectId()).toBe('proj-from-file');
      expect(connectorProjectContext().projectId).toBe('proj-from-file');
      expect(process.env.NOT_ALLOWLISTED).toBeUndefined();
      expect(process.env.AGENTMAIL_API_KEY).toBeUndefined();
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });

  it('does NOT treat ZED_TOKEN (the sandbox service key) as a CLI token', () => {
    process.env.ZED_TOKEN = 'zed_sb_sandboxkey';
    // With no CLI/connector token and a missing config file we fall through to
    // the default (logged-out) host — crucially, the sandbox key is never
    // adopted as the active token. `resolveProjectContext` treats an empty
    // token as "not logged in".
    expect(activeHost()?.token || '').not.toBe('zed_sb_sandboxkey');
    expect(activeHost()?.token || '').toBe('');
  });

  it('reads the project id from ZED_PROJECT_ID', () => {
    process.env.ZED_PROJECT_ID = 'proj-xyz';
    expect(resolveProjectId()).toBe('proj-xyz');
  });

  it('lets connector management commands override ZED_PROJECT_ID with --project', () => {
    process.env.ZED_CLI_TOKEN = 'zed_pat_cli';
    process.env.ZED_API_URL = 'https://tunnel.example/v1';
    process.env.ZED_PROJECT_ID = 'proj-from-env';

    expect(connectorProjectContext('proj-from-flag').projectId).toBe('proj-from-flag');
  });
});

describe('env token vs .zed/link.json host', () => {
  // A repo may carry a committed link.json naming a host (per-repo binding).
  // Inside a session sandbox that named host has no stored credentials, so
  // the platform-injected env token must outrank it — otherwise every
  // project-scoped command dies with "host not logged in".
  let dir: string;
  let savedCwd: string;

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'zed-cli-link-'));
    mkdirSync(join(dir, '.zed'), { recursive: true });
    writeFileSync(
      join(dir, '.zed', 'link.json'),
      JSON.stringify({
        project_id: 'proj-from-link',
        account_id: 'acct',
        host: 'zed-internal-dev',
        linked_at: '2026-01-01T00:00:00.000Z',
      }),
    );
    savedCwd = process.cwd();
    process.chdir(dir);
  });

  afterEach(() => {
    process.chdir(savedCwd);
    rmSync(dir, { recursive: true, force: true });
  });

  it('resolveProjectContext uses the env token even when link.json names a host', async () => {
    process.env.ZED_CLI_TOKEN = 'zed_pat_cli';
    process.env.ZED_API_URL = 'https://tunnel.example/v1';
    const ctx = await resolveProjectContext();
    expect(ctx).not.toBeNull();
    expect(ctx?.auth.token).toBe('zed_pat_cli');
    expect(ctx?.auth.api_base).toBe('https://tunnel.example/v1');
    // Project still comes from the link — only the HOST binding is overridden.
    expect(ctx?.projectId).toBe('proj-from-link');
  });

  it('without an env token the link host is still honored (and fails logged-out)', async () => {
    // Config file points at a nonexistent path → the named host has no token →
    // the pre-existing behavior (refuse with "not logged in") is preserved.
    const ctx = await resolveProjectContext();
    expect(ctx).toBeNull();
  });

  it('an explicit --host override still wins over the env token', async () => {
    process.env.ZED_CLI_TOKEN = 'zed_pat_cli';
    // 'nonexistent-host' has no credentials → context resolution must fail
    // rather than silently falling back to the env token the caller did not ask for.
    const ctx = await resolveProjectContext({ hostArg: 'nonexistent-host' });
    expect(ctx).toBeNull();
  });
});

describe('API URL joining', () => {
  let calls: string[];
  const realFetch = globalThis.fetch;

  beforeEach(() => {
    calls = [];
    globalThis.fetch = (async (url: string) => {
      calls.push(String(url));
      return new Response(JSON.stringify({ ok: true }), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      });
    }) as unknown as typeof fetch;
  });
  afterEach(() => {
    globalThis.fetch = realFetch;
  });

  it('does not double the /v1 mount when the base already ends in /v1', async () => {
    // This is exactly the sandbox shape: ZED_API_URL = https://<tunnel>/v1
    const client = createApiClient({ apiBase: 'https://tunnel.example/v1', token: 't' });
    await client.get('/projects/p1/change-requests');
    expect(calls[0]).toBe('https://tunnel.example/v1/projects/p1/change-requests');
  });

  it('adds the /v1 mount when the base is a bare origin', async () => {
    const client = createApiClient({ apiBase: 'https://api.zed.com', token: 't' });
    await client.get('/projects/p1/change-requests');
    expect(calls[0]).toBe('https://api.zed.com/v1/projects/p1/change-requests');
  });

  it('tolerates a trailing slash on the base', async () => {
    const client = createApiClient({ apiBase: 'https://tunnel.example/v1/', token: 't' });
    await client.get('/projects/p1/change-requests');
    expect(calls[0]).toBe('https://tunnel.example/v1/projects/p1/change-requests');
  });
});
